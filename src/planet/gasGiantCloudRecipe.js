// 气态巨星的**云层配方**（唯一真源）。
//
// ===========================================================================
//  它是什么：**不透明的可见表面**，而不是"盖在别的东西上的云"
// ===========================================================================
//  地球：    albedo 地表  →  [云层：α 是「有没有云」的遮罩，有晴区]  →  大气散射
//  气态巨星： [云层：α ≡ 1，云顶**就是**可见表面]                    →  大气散射
//
//  ⇒ 两者问的问题不一样：
//      地球的云问「这一像素**有没有**云」   ⇒ 阈值口径（coverage / CDF / softness）
//      巨星的云问「这一像素的云顶**是什么**」⇒ 逐纬度色表 + 乘性纹理
//  ⇒ **α 与颜色的来源必须分开**，只在噪声内核（噪声 / 域扭曲 / 脊线 / 方向换算）
//    与光照/大气口径上共享 —— 内核的唯一真源是 shaders/cloudFieldGLSL.js 的
//    `cloudNoiseGLSL()`，本文件的 GLSL 装配（shaders/gasGiantCloudGLSL.js）调它。
//
// ===========================================================================
//  模型（三行说清，第 1 步）
// ===========================================================================
//      lat(像素)  = asin(本地位置.y)                    ← 解析求，与 uv 参数无关
//      latEff     = lat + edgeAmount · (edgeNoise − 0.5) ← 带缘随经度摆动/撕裂
//      albedo     = 色表(latEff) · (1 + texAmp · (b − 0.5))   ← b 是面积均匀的场值
//      α          = 1（盘面内恒为 1）
//
//  ⚠️ **为什么纬度不能用 uv.y**：uv 是等距圆柱**参数**，而网格渲染出来的是
//     **远半球**（见 cloudShaders.js 文件头）。在远半球上 v 与屏幕位置的关系是
//     `v = sqrt(1 − y²)/2 + 0.5`，**不是** y 的线性函数 ⇒ 拿 uv.y 当纬度会得到
//     一个盘心为极点、盘缘为赤道的错误映射。
//     `asin(本地位置.y)` 没有这个问题：球面点的法线**就是**它的方向，
//     而正交投影下屏幕 y 就等于方向的 y 分量 ⇒ lat = asin(y) 是定义式。
//
// ===========================================================================
//  数据来源（三张表，全部可复现）
// ===========================================================================
//   `node tools/measureReferenceDisc.mjs data/bop-src/jool.png --delight --tables`
//   扫 `data/bop-src/jool.png`（2548×2545 正交圆盘）的产物，逐条口径见
//   `docs/气态巨星参照实测.md`。要点：
//     · 节点 = **−90..+90 每 2°**，共 91 点
//     · 亮度 = **去光后**的 ±2° 平滑纬度剖面（"去光"见下）
//     · 颜色 = 逐纬度加权平均 sRGB 的**三通道比例**缩放到该纬度亮度，再转线性
//     · ⚠️ |lat| > 71.8° **没有实测样本**（几何：盘面上 r ≥ |sin lat|），
//       那两个区间用最外 10° 的斜率线性外推再向球面均值收拢 —— 只为"不外推失控"，
//       **不是实测**，改动它们不需要任何依据、也不能声称有依据
//
// ===========================================================================
//  ★★ 为什么目标数必须取"去光后" ★★
// ===========================================================================
//   参照图是**打了光的球**：拟合 luma ≈ c0 + c1·dx + c2·dy + c3·z 得
//     光方向 (0.483, −0.069, 0.873)（偏离相机轴 29.2°）、幅度 **24.27/255**、
//     R² = 0.225（该线性形式**正是**朗伯+常数环境光的严格解）。
//   而反照率带纹的 σ 只有 9.3/255 ⇒ **光照是带纹对比的 2.6 倍**。
//   直接把原始像素当色表 = 把参照的光烘进反照率，渲染时再乘一次自己的光
//   ⇒ 双重着色，且带纹被梯度淹掉。所以本文件的表一律来自 `--delight` 口径。
//
// ===========================================================================
//  口径警告（改这个文件前必读）
// ===========================================================================
//   1. 表是 −90..+90 每 2°、共 91 点。改步长必须同时改 GLSL 侧常量与校验。
//   2. 全部颜色是**线性 RGB**（着色器的光照在线性空间做）。存 sRGB 会让盘面整体偏亮。
//   3. 饱和度是**实测**的（0.43..0.64，均值 0.54），不是一个可以大范围摆动的旋钮。
//      要调观感请调 texAmp / 光照 / edgeAmount，不要靠加饱和救场。
//   4. seed 必须 < 2²⁴（float32 精度：超界时 GPU 会算出一个**完全无关**的场，
//      而且画面看着仍然像云，只有 CPU↔GPU 对拍能发现）。

// ★★ 数据表从**生成物**导入（本文件只放逻辑与参数）★★
//   91 点 ×4 张表由下面这条命令生成，**不要手抄**：
//     node tools/measureReferenceDisc.mjs <png> --delight --tables --latmax 50 \
//          --emit-module src/planet/gasGiantBandTables.js
//   手抄 364 个数必然出错，而错了以后画面**看着仍然像行星**，肉眼分辨不出来。
