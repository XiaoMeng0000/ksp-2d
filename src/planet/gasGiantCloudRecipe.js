/** sRGB → 线性 */
function srgbToLinear(c) {
    return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
}

/** 线性 → sRGB */
function linearToSrgb(c) {
    const x = Math.max(0, Math.min(1, c));
    return x <= 0.0031308 ? x * 12.92 : 1.055 * Math.pow(x, 1 / 2.4) - 0.055;
}

/** 逐节点的 sRGB 亮度（与测参照时同一口径 = Rec.601 on sRGB） */
function bandLumaSrgb(i) {
    return 0.299 * linearToSrgb(GG_COLOR_R[i])
        + 0.587 * linearToSrgb(GG_COLOR_G[i])
        + 0.114 * linearToSrgb(GG_COLOR_B[i]);
}

/**
 * ★★ 带纹**陡度**（由色表中心差分求，**不新增数据表**）★★
 *
 * ★ 为什么不用 sRGB 亮度、改成**线性亮度** ★
 *   181 点 ×4 张表会超出 WebGL2 保证的 uniform 下限（224 个 vec4）
 *   ⇒ 把陡度表**去掉**，改成在着色器里现算。
 *   现算要做 2 次额外查表 + 一次中心差分；若还按 sRGB 亮度算，就要 6 次 pow
 *   ⇒ 改用**线性**亮度（`0.299R+0.587G+0.114B`，线性表上直接算，零 pow）。
 *   形状与 sRGB 口径略有差别，但这一项是"幅度长在哪"的**调制形状**、不是被测量，
 *   所以可以接受 —— **这里如实记下这个口径差异**。
 *
 * ★ 驱动量是实测出来的（n=140，去光口径，新参照 gg-ref-2.png）★
 *     带的**陡度** r = **+0.643**（最强）
 *     **纬度**     r = −0.197
 *     带的**幅度** r = −0.262（不是驱动）
 *   ⇒ **不是"越亮越暗的带越乱"，是"越过界越乱"** —— 正是「靠云带的排列」。
 */
const SLOPE_RAW = (function () {
    const n = GG_TABLE_POINTS;
    const luma = new Float64Array(n);
    for (let i = 0; i < n; i++) {
        luma[i] = 0.299 * GG_COLOR_R[i] + 0.587 * GG_COLOR_G[i] + 0.114 * GG_COLOR_B[i];
    }
    const s = new Float64Array(n);
    for (let i = 0; i < n; i++) {
        const a = luma[Math.max(0, i - 1)];
        const b = luma[Math.min(n - 1, i + 1)];
        s[i] = Math.abs(b - a) / 2;
    }
    return s;
})();

/** 陡度的最大值（归一化用；着色器里也要用同一个数） */
export const GG_SLOPE_MAX = (function () {
    let mx = 0;
    for (let i = 0; i < SLOPE_RAW.length; i++) {
        if (SLOPE_RAW[i] > mx) {
            mx = SLOPE_RAW[i];
        }
    }
    return mx;
})();

/**
 * ★★ 急流廓线 `P(lat)` —— **零新增数据**，就是上面那条陡度的**带符号版** ★★
 *
 * 物理依据：木星的**东向急流在亮带、西向急流在暗带**，而急流的**峰值在带界**、
 *   带中心为零。这正好就是 `d(亮度)/dlat` 的形状 ⇒ 用它当廓线，
 *   **带的数量直接变成急流的数量**（14 条带 ⇒ 14 条急流），一个数都不用新加。
 *
 * 三条处理：
 *   ① 用**带符号**的陡度（上面 `SLOPE_RAW` 是绝对值，纹理幅度要用它；这里要方向）
 *   ② 减去**面积加权均值**并重新归一化 ⇒ `P` 的球面均值为 0（纯**相对**流动，
 *      盘面不会整体漂）且仍落在 [−1, 1]
 *   ③ 归一化到 [−1, 1] ⇒ 着色器里的位移上界**恒等于** `jetAmp`（有界那条铁律）
 */
export const GG_JET_PROFILE = (function buildJetProfile() {
    const n = GG_TABLE_POINTS;
    const luma = new Float64Array(n);
    for (let i = 0; i < n; i++) {
        luma[i] = 0.299 * GG_COLOR_R[i] + 0.587 * GG_COLOR_G[i] + 0.114 * GG_COLOR_B[i];
    }
    const sgn = new Float64Array(n);
    for (let i = 0; i < n; i++) {
        const a = luma[Math.max(0, i - 1)];
        const b = luma[Math.min(n - 1, i + 1)];
        sgn[i] = (b - a) / 2;                 // ★ 不取绝对值：方向就是急流方向
    }
    // ② 扣掉面积加权均值（cos 纬度权重）
    let wSum = 0;
    let sSum = 0;
    for (let i = 0; i < n; i++) {
        const lat = GG_LAT_MIN + GG_LAT_STEP * i;
        const w = Math.cos(lat * Math.PI / 180);
        wSum += w;
        sSum += w * sgn[i];
    }
    const mean = sSum / wSum;
    for (let i = 0; i < n; i++) {
        sgn[i] -= mean;
    }
    // ③ 归一化到 [−1, 1]
    let mx = 0;
    for (let i = 0; i < n; i++) {
        mx = Math.max(mx, Math.abs(sgn[i]));
    }
    const out = new Array(n);
    for (let i = 0; i < n; i++) {
        out[i] = mx > 0 ? sgn[i] / mx : 0;
    }
    return out;
})();

/** `GG_JET_PROFILE` 的符号翻转统计（自检用：必须**交替**，否则廓线写错了） */
export const GG_JET_SIGN_FLIPS = (function () {
    let flips = 0;
    for (let i = 1; i < GG_JET_PROFILE.length; i++) {
        if (GG_JET_PROFILE[i] * GG_JET_PROFILE[i - 1] < 0) {
            flips++;
        }
    }
    return flips;
})();

/** 归一化陡度的**面积加权均值**（居中用，让幅度调制的均值恒为 1） */
export const GG_SLOPE_AREA_MEAN = (function () {
    let w = 0;
    let s = 0;
    for (let i = 0; i < GG_TABLE_POINTS; i++) {
        const lat = GG_LAT_MIN + GG_LAT_STEP * i;
        const cw = Math.cos(lat * Math.PI / 180);
        w += cw;
        s += cw * (GG_SLOPE_MAX > 0 ? SLOPE_RAW[i] / GG_SLOPE_MAX : 0);
    }
    return s / w;
})();

/**
 * `1 − |lat|/90` 的**面积加权均值**（赤道最乱、高纬最静那一条的居中量）。
 * 解析值 = 1 − (π/2 − 1)·2/π ≈ 0.6366，这里数值算一遍以免手抄错。
 */
export const GG_ENV_AREA_MEAN = (function () {
    let w = 0;
    let s = 0;
    for (let i = 0; i < GG_TABLE_POINTS; i++) {
        const lat = GG_LAT_MIN + GG_LAT_STEP * i;
        const cw = Math.cos(lat * Math.PI / 180);
        w += cw;
        s += cw * (1 - Math.abs(lat) / 90);
    }
    return s / w;
})();

/**
 * ★ 装配期自检 ★
 *
 * 证明色表与亮度表是**同一件事的两种写法**：把线性 RGB 转回 sRGB、
 * 取 Rec.601 亮度，必须逐点等于 GG_BAND_LUMA_SRGB。
 * 这条断言能抓住"手改了颜色忘了改亮度""sRGB/线性转错一次"这类静默错误 ——
 * 它们的症状都是盘面整体偏亮或偏暗，而画面看着仍然"像颗行星"。
 *
 * @returns {{maxErr:number, meanLuma:number, bandSigma255:number}}
 * @throws {Error} 表长不符或自检超差时 —— **不静默通过**
 */
export function verifyGasGiantTables() {
    const n = GG_TABLE_POINTS;
    if (GG_BAND_LUMA_SRGB.length !== n || GG_COLOR_R.length !== n
        || GG_COLOR_G.length !== n || GG_COLOR_B.length !== n) {
        throw new Error('气态巨星色表长度不符：应为 ' + n + ' 点，实测 '
            + [GG_BAND_LUMA_SRGB, GG_COLOR_R, GG_COLOR_G, GG_COLOR_B]
                .map((a) => a.length).join('/'));
    }
    let maxErr = 0;
    let wSum = 0;
    let wLuma = 0;
    for (let i = 0; i < n; i++) {
        const lat = GG_LAT_MIN + GG_LAT_STEP * i;
        const r = linearToSrgb(GG_COLOR_R[i]);
        const g = linearToSrgb(GG_COLOR_G[i]);
        const b = linearToSrgb(GG_COLOR_B[i]);
        const luma = 0.299 * r + 0.587 * g + 0.114 * b;
        maxErr = Math.max(maxErr, Math.abs(luma - GG_BAND_LUMA_SRGB[i]));
        const w = Math.cos(lat * Math.PI / 180);
        wSum += w;
        wLuma += w * luma;
    }
    if (maxErr > 1e-4) {
        throw new Error('气态巨星色表自检失败：线性 RGB 转回 sRGB 后的亮度与亮度表'
            + '最大差 ' + maxErr.toFixed(6) + '（应 < 1e-4）。'
            + '症状会是盘面整体偏亮/偏暗 —— 请检查是否有人只改了其中一张表。');
    }
    // 带纹 σ：面积加权（这条同时是"带纹确实存在"的守卫）
    const meanLuma = wLuma / wSum;
    let v = 0;
    for (let i = 0; i < n; i++) {
        const lat = GG_LAT_MIN + GG_LAT_STEP * i;
        const r = linearToSrgb(GG_COLOR_R[i]);
        const g = linearToSrgb(GG_COLOR_G[i]);
        const b = linearToSrgb(GG_COLOR_B[i]);
        const luma = 0.299 * r + 0.587 * g + 0.114 * b;
        const w = Math.cos(lat * Math.PI / 180);
        v += w * (luma - meanLuma) * (luma - meanLuma);
    }
    return {
        maxErr: maxErr,
        meanLuma: meanLuma,
        bandSigma255: Math.sqrt(v / wSum) * 255,
    };
}

