/**
 * ⚠️【已废弃，2026-10-02】空气质量下限的旧默认值。**代码里已不再使用。**
 *
 * 它曾是经验式 `airMass = (1+f)/max(f, cosZ+f)` 里的地板 f。那条曲线不是物理量，
 * 且在掠射端系统性偏大：用本项目几何（H/R = 0.013、大气外径 1.30）实测，
 * 地平线处真值 **11.05**、经验式 **38.04**（偏高 244%）⇒ 红光被过早杀光。
 *
 * 空气质量现在由 **src/planet/airMass.js** 的「二维太阳柱积分表」
 * （高度 × 太阳高度余弦）给出；本体与大气共用同一张表 ⇒ 口径不可能漂移，
 * 而且"消光发生在哪一段路径上"这件事终于是对的（见该文件头）。
 *
 * 保留下面的历史记录只为追溯；新代码**不要**引用本常量。
 *
 * ★★ 名字改了，0.01 → 0.027（2026-09-27）★★
 *   旧名「日落红强度」**严重误导** —— 它让人以为这是个调色参数，
 *   实际它设的是**最大空气质量** `1 + 1/f`，而空气质量是乘在
 *   **整条大气的光学厚度**上的（`sunT = exp(-βExt · H · dens · airMass)`）。
 *   所以它同时决定三件事：
 *     ① 晨昏线的红化程度
 *     ② 临边大气带的**亮度**（实测 ×2.8 摆幅）
 *     ③ 临边到底是「**暖色发光带**」还是「**一块黑灰**」
 */
export const DEFAULT_AIR_MASS_FLOOR = 0.027;

/**
 * 由大气参数算出**消光系数**（RGB）= Rayleigh + Mie + 吸收。
 *
 * 为什么单独抽出来：星球本体的光照（planetShaders 的日落红）与大气散射层
 * 必须用**同一份**消光口径 —— 否则一处改了另一处不知道，日落红会对不上。
 *
 * ★ tint 不参与消光（2026-09-26 修正）★
 *
 * tint 是给天空调色的**艺术参数**（Jool 绿 / Eve 紫），没有物理依据。早先它被
 * 一并乘进了消光，后果是连**直射阳光的衰减**也被改掉 —— 正午白平衡被拉暖：
 * Kerbin 冰盖从白 (228,236,236) 变淡黄 (223,217,163)，草地从青绿变橄榄绿。
 * 而 Rayleigh 本身的配比 β_B/β_G = 2.23 已经与真实 1/λ⁴ 完全一致，乘 tint 后
 * 变成 3.58 ⇒ 蓝通道消光超标 89%（0.414 vs 真实 0.219）。
 * 现在 tint 只作用在散射源项（见 atmosphereShaders 的 betaR / betaM），
 * 消光走纯物理口径。修正后 5 个太阳高度角全部命中真实地球：
 * 正午 R/B 1.17 vs 1.18、66° 1.46 vs 1.51、日落带 4.08 vs 4.70。
 *
 * @param {object} atmo 大气参数（含 rayleigh / mie / absorb；**tint 不参与**）
 * @returns {Array<number>} [r, g, b]
 */
export function solveExtinction(atmo) {
    const a = atmo || {};
    const rayleigh = a.rayleigh || [0, 0, 0];
    const absorb = a.absorb || [0, 0, 0];
    // Mie 在本模型里是**消色差**的单一标量 ⇒ 等权加到三个通道，不乘 tint
    const mie = a.mie || 0;
    return [0, 1, 2].map((c) => rayleigh[c] + mie + absorb[c]);
}

/**
 * 垂直方向的**散射光深**（标量）= (β_R + β_M) · H，取三通道均值。
 *
 * ★ 用途：镜面高光的"被大气抹开多少"（见 planetShaders 的 uAtmoScatterOd）★
 *
 * ⚠️ 为什么不用**气溶胶**光深：Kerbin 的配方里 `mie = 0`（成分中没有霾/尘埃），
 *    用 Mie 会让这一项对 Kerbin 恒等于 0 —— 而分子散射同样会把高光抹开。
 *    用总散射光深对所有配方都成立，且量级正确。
 *
 * ⚠️ 为什么取三通道**均值**：这一项只用来定"抹开多少"，是几何/模糊量、不是颜色量。
 *    高光的颜色由着色器里的 sunTint（阳光穿过大气后的颜色）负责。
 *
 * @param {object} atmo 大气参数（solveMixture 的返回）
 * @returns {number} 无量纲光深；atmo 为空时返回 0
 */
export function solveScatterOpticalDepth(atmo) {
    if (!atmo) {
        return 0;
    }
    const h = atmo.scaleHeight || 0;
    const rayleigh = atmo.rayleigh || [0, 0, 0];
    const mie = atmo.mie || 0;
    return ((rayleigh[0] + rayleigh[1] + rayleigh[2]) / 3 + mie) * h;
}

/**
 * 由配方算出渲染用的散射/吸收参数。
 *
 * 计算链条：
 *   1. 混合折射率：(n−1)_mix = Σ xᵢ(n−1)ᵢ   （Gladstone-Dale 关系，体积加权）
 *   2. Rayleigh 系数：以地球式大气为基准，按 (n−1)² 的相对浓淡缩放
 *      （平方来自 (n²−1)²；色相沿用 BETA_REF 的 λ⁻⁴ 比例 —— 见文件头结论）
 *   3. 吸收系数：Σ xᵢ·absorbᵢ，再乘 BETA_REF 保持量级一致
 *   4. Mie 系数：Σ xᵢ·mieᵢ
 *
 * @param {string} id 配方 id（MIXTURES 的键）
 * @param {object} [opts]
 * @param {number} [opts.concentration=1] 总浓度倍数（1 = 基准）
 * @param {Array<number>} [opts.tintOverride] 覆盖配方自带的色调
 * @returns {object|null} { rayleigh, absorb, mie, tint, atmoScale, scaleHeight, label, nm1 }
 */
export function solveMixture(id, opts) {
    const mix = MIXTURES[id];
    if (!mix) {
        return null;
    }
    const o = opts || {};
    // 总浓度 = 天体基准（配方自带）× 用户倍数（面板滑块）
    const conc = (mix.concentration === undefined ? 1 : mix.concentration)
        * (o.concentration === undefined ? 1 : o.concentration);

    let nm1 = 0;
    let mie = 0;
    const absorbFrac = [0, 0, 0];
    Object.keys(mix.mix).forEach((sid) => {
        const s = SPECIES[sid];
        if (!s) {
            return;
        }
        const frac = mix.mix[sid];
        if (s.kind === 'gas') {
            nm1 += frac * s.nm1;
        }
        if (s.absorb) {
            absorbFrac[0] += frac * s.absorb[0];
            absorbFrac[1] += frac * s.absorb[1];
            absorbFrac[2] += frac * s.absorb[2];
        }
        if (s.mie) {
            mie += frac * s.mie;
        }
    });

    const rel = nm1 / RAYLEIGH_REF_NM1;          // 相对地球的浓淡
    const rayleigh = [0, 1, 2].map(
        (c) => BETA_REF[c] * rel * rel * DISPERSION[c] * conc,
    );
    const absorb = [0, 1, 2].map((c) => absorbFrac[c] * BETA_REF[c] * conc);
    // Mie 也用 BETA_REF 作基准缩放，否则它永远比 Rayleigh 小几个数量级、
    // 在观感上等于没有（尘埃/硫酸雾这类"散射主导"的成分就体现不出来）
    const mieCoeff = mie * BETA_REF[1] * conc;
    const tint = o.tintOverride || mix.tint || [1, 1, 1];

    return {
        label: mix.label,
        nm1,
        rayleigh,
        absorb,
        mie: mieCoeff,
        tint,
        atmoScale: mix.atmoScale,
        scaleHeight: mix.scaleHeight,
        // 渲染侧观感参数：一颗天体一整套，切配方即切全套
        mieG: mix.mieG,
        multiScatter: mix.multiScatter,
        selfAbsorb: mix.selfAbsorb,
        intensity: mix.intensity,
        // 临边高光软压缩的膝点（未声明该字段的配方 = 0 = 关闭 = 历史口径）
        softKnee: mix.softKnee === undefined ? 0 : mix.softKnee,
        // 注：日落红强度（airMassFloor）**不在这里** —— 它是大气层的通用物理参数
        //     （空气质量/Chapman 量级，所有天体同一档），由 atmosphereLayer 的默认值
        //     统一提供、面板可调。放进配方会让"通用能力"变成"某颗天体的特例"。
    };
}
