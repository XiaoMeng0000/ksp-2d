//     成分 → 混合折射率 → Rayleigh 散射系数（RGB）
//     成分 → 吸收性物质 → 吸收系数（RGB）→ 这才是**色相**的来源
//
// ⚠️ 一条必须先知道的实测结论（别指望"换气体"能改颜色）：
//   Rayleigh 的色相几乎完全由 1/λ⁴ 决定。实测把地球（N₂/O₂）、火星（CO₂）、
//   Titan（N₂/CH₄）、金星（CO₂）、Jool（H₂/He）、Eve（SO₂）六种配方分别代入，
//   归一化后的 RGB 比例**全部是 0.425 : 1 : 2.500**（偏差 < 2.4%）。
//   原因：不同气体的折射率色散差异只有 1~2%，而 λ⁴ 因子跨 RGB 是 5.7 倍。
//   ⇒ **成分能改的是「浓淡」（n−1 相差最多约 4 倍），色相必须靠吸收/霾。**
//   这与真实天体一致：Titan 的橙色天空来自有机霾吸收蓝光，火星的黄褐来自尘埃。
//
// ★ 数据来源与精度声明 ★
//   · 气体折射率：标准条件下的公开值（589nm, 0°C, 1atm），取 4 位有效数字。
//     游戏用途，不做光谱级精度。
//   · 吸收系数：**不是**实测值，是按"该物质在大气中的典型含量下能产生
//     可见色偏"反推的等效强度（臭氧用很大的值，因为它的吸收截面极大、
//     而含量极低 —— 这正是真实地球天空偏蓝的原因之一）。
//   · tint（色调乘子）：**艺术指定色**，没有物理依据，用于 Jool 绿 / Eve 紫
//     这类虚构配色。用它时请在文档里注明"这是设计值"。
//     ⚠️ 它**只作用在散射源项**（天空的颜色），**不参与消光** —— 见 solveExtinction。
