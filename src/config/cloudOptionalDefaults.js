// 字段与单位：
//   slopeEps  rad   自阴影/高度反照率的差分步长（b 沿太阳切向的方向导数）
//   edgeRel   1     云缘过渡宽度里"随盘半径伸缩"的份额（× 屏幕盘半径，像素）
//   edgeKnee  1     云缘"薄边"强度（按光学厚度 τ 渐薄，对比度软压缩）
//
// ⚠️ 三个默认值都**不改变画面**（逐像素）：
//   slopeEps 0.05 = 第二卷 A 之前的硬编码差分步长（≈2.9°，slope 段默认走该常量路径）；
//   edgeRel  0    = 只用 edgePx 的绝对口径（相对份额恒为 0）；
//   edgeKnee 0    = 云缘薄边关闭（整段分支不执行）。
//   ⇒ 改这三个默认值 = 改编画面基线，必须重跑零回归。
//
// 来源：第二卷 A（task-2）的因果验证参数；总监 2026-10-23 裁决要求默认值入 src/config/。

/**
 * 可选参数的面板/着色器默认值。
 * @type {{slopeEps:number, edgeRel:number, edgeKnee:number,
 *         shells:number, shellGap:number, shellDim:number, innerOctaves:number}}
 */
export const CLOUD_OPTIONAL_DEFAULTS = Object.freeze({
    slopeEps: 0.05,
    edgeRel: 0,
    edgeKnee: 0,

    // ---- 第三卷：多层壳（2026-10-23 **已采纳为默认**）----
    //   云内 0.2~3° 的层次只能来自"不同高度的云各自吃光、互相遮蔽"（单层已被 Q1 证否）。
    //   ★ 2026-10-23 总监采纳：shells=2 + 每壳独立场（shellShift 0.13）+ 云量补偿 0.7
    //     + 内层降倍频 1 ⇒ 云内 D/mean（相对 1 壳）0.26/0.70/1.05/2.11° = +40/+88/+81/+54%。
    //   ⚠️ 因此**默认画面已不是第二卷的 1 壳画面** —— 零回归的对照物是
    //      `data/out/vol3/final-baseline/`（新基线），**不是** `data/out/nearview/`（旧基线）。
    /** 壳数 1~3（1 = 第二卷的单层画面；自适应：盘半径大 ⇒ 2，小 ⇒ 1） */
    shells: 2,
    /** 相邻壳的半径差（占星径比例）：壳 k 的半径 = 1 − shellGap·k */
    shellGap: 0.004,
    /** 内层亮度衰减（光穿过上面几层后变暗）；1 = 不衰减 */
    shellDim: 0.6,
    /** 内层倍频数（"内层降倍频"）；外层仍用配方里的倍频数（6）。采纳值 = 1（省电、也不容易露出假纹理） */
    innerOctaves: 1,
    // ---- 第三卷 A：每壳独立场（总监 2026-10-23 裁决：不同高度的云是**不同的云**）----
    //   实现是**内层经度偏移**（壳 k 偏 k·shellShift），不是换 seed：
    //   换 seed 会改 b 的分布（CDF 按配方 seed 烘）⇒ 每层覆盖率语义都会偏；
    //   同一张场挪经度则统计性质完全不变（覆盖率、能量都不变）。
    /** 内层经度偏移（u 的比例）；0 = 退回"同一个场"（已被几何否决的那一档，留作对照组） */
    shellShift: 0.13,
    /** 多壳覆盖率补偿（并集守恒）：每层 c' = 1 − (1 − coverage)^(1/N)；0 = 不补偿（并集会变大） */
    //   采纳值 0.7（按"画面云量"标定）：补偿后云量 1.80% vs 1 壳的 2.04%（−12%，总监已接受）。
    shellCoverageComp: 0.7,

    // ---- 第三卷：云影（2026-10-23 总监只批了这一个新增 target）----
    //   512×256 等距柱状小图：每个 texel = 竖直穿过各层云壳的光学厚度 τ，
    //   输出 shade = 1 − exp(−τ)；地表按"沿太阳方向穿到云壳的交点"去查这张图
    //   （视差 ⇒ 影与云错位；夜面因为只乘直射光项 ⇒ 数学上无影）。
    /** 是否启用云影。**默认 true**（2026-10-23 采纳）；关掉时连 target 都不创建、地表 uniform 全关 */
    shadowEnabled: true,
    /** 影的强度：0 = 无影，1 = 完全挡掉直射光 */
    shadowStrength: 0.7,
    /** 视差系数：1 = 真实（影子与云错位）；0 = 影子落在云正下方（**只用于量错位幅度的对照**） */
    shadowParallax: 1,
});

