//       其余按版本从早到晚(当前版本取自 version.js;无当前版本时最早的在最上)。
// 版本号带字母后缀(如 v0.2.4beta)视为子版本:不识别为当前版本,排序在无后缀版本之后。
// ============================================================

// 提取版本段:数字 + 可选字母后缀 → 'v0.2.4-alpha (Build 202608)' → [0, 2, 4];
//   'v0.2.4beta' → [0, 2, 4, 'beta'](字母后缀视为子版本,如 beta 测试版)
function _parseVersion(v) {
    const m = String(v).match(/^v?(\d+(?:\.\d+)*)([a-z]*)/i);
    if (!m) return [];
    const nums = m[1].split('.').map(Number);
    const suffix = m[2].toLowerCase();
    return suffix ? nums.concat(suffix) : nums;
}

// 比较两个版本号:早 → 晚(数字段按数值,字母后缀按字典序;缺失段视为早于有值段,
//   因此 'v0.2.4' 早于 'v0.2.4beta',beta 条目也不会被识别为当前版本)
function _compareVersions(a, b) {
    const pa = _parseVersion(a);
    const pb = _parseVersion(b);
    const len = Math.max(pa.length, pb.length);
    for (let i = 0; i < len; i++) {
        const x = pa[i];
        const y = pb[i];
        if (x === undefined) return -1;
        if (y === undefined) return 1;
        if (typeof x === 'number' && typeof y === 'number') {
            if (x < y) return -1;
            if (x > y) return 1;
        } else if (x !== y) {
            return String(x).localeCompare(String(y), 'en');
        }
    }
    return 0;
}

// 是否为当前版本公告(与 VERSION_TEXT 比较,忽略 -alpha 等后缀与 Build 号)
function _isCurrentVersion(v) {
    return _compareVersions(v, VERSION_TEXT) === 0;
}

