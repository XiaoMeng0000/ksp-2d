// 提取版本数字段:'v0.2.4-alpha (Build 202608)' → [0, 2, 4]
function _parseVersion(v) {
    const m = String(v).match(/^v?(\d+(?:\.\d+)*)/);
    return m ? m[1].split('.').map(Number) : [];
}

// 比较两个版本号:早 → 晚(缺失段补 0)
function _compareVersions(a, b) {
    const pa = _parseVersion(a);
    const pb = _parseVersion(b);
    const len = Math.max(pa.length, pb.length);
    for (let i = 0; i < len; i++) {
        const x = pa[i] || 0;
        const y = pb[i] || 0;
        if (x < y) return -1;
        if (x > y) return 1;
    }
    return 0;
}

// 是否为当前版本公告(与 VERSION_TEXT 比较,忽略 -alpha 等后缀与 Build 号)
function _isCurrentVersion(v) {
    return _compareVersions(v, VERSION_TEXT) === 0;
}

